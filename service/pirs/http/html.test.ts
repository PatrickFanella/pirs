import assert from 'node:assert/strict'
import { test } from 'node:test'
import { parse } from 'parse5'
import { staticHtml } from './html.ts'

test('HTML5 projection removes navigation in malformed, encoded and foreign HTML', () => {
  const attacks = [
    `<A HREF="http&#58;//127.0.0.1/session" target=_self ping=/session download>ordinary</A>`,
    `<base href="http://127.0.0.1/"><a href=/session>relative</a>`,
    `<form action=/session><button formaction=/session>submit</button></form>`,
    `<svg><a xlink:href="http://127.0.0.1/session"><text>SVG link</text></a></svg>`,
    `<math><annotation-xml encoding="text/html"><a href=/session>foreign</a></annotation-xml></math>`,
    `<meta http-equiv=refresh content="0;url=/session"><iframe srcdoc="<a href=/session>frame</a>"></iframe>`,
    `<table><a href=/session><tr><td>foster parenting</table>`,
    `<noscript><p title="</noscript><a href=/session>escape</a>">text</p>`,
    `<p title='" onmouseover="location=/session'>&lt;a href=/session&gt;</p>`,
    `<style>@import url(/session)</style><div style="background:url(/session)">CSS</div>`,
    `<a href=/session href=/other onclick="location='/session'">duplicate</a>`
  ]
  for (const source of attacks) {
    const result = staticHtml(source, 16384)
    // Reparse generated bytes with both scripting modes. No source strings are
    // trusted as markup; only known inert attributes may survive tree repair.
    for (const scriptingEnabled of [true, false]) {
      const pending: any[] = [parse(result, { scriptingEnabled })]
      while (pending.length) {
        const node = pending.pop()
        if (node.tagName) {
          assert.equal(node.namespaceURI, 'http://www.w3.org/1999/xhtml')
          assert.ok(!['script', 'style', 'form', 'iframe', 'meta', 'base', 'img', 'svg', 'math'].includes(node.tagName), source)
          for (const attr of node.attrs) assert.ok(['id', 'title', 'lang', 'dir', 'colspan', 'rowspan', 'type'].includes(attr.name), source)
        }
        pending.push(...(node.childNodes ?? []))
      }
    }
  }
})

test('static HTML retains semantic formatting and bounds serialized bytes', () => {
  const source = `<h1>Heading</h1><p>Hello <strong>guest</strong></p><ul><li>Item</li></ul><table><tr><th>Name</th><td colspan=2>Value</td></tr></table><details><summary>Expand</summary><p>Details</p></details><a href=/session>Link label</a>`
  const output = staticHtml(source, 4096)
  for (const expected of ['<h1>Heading</h1>', '<strong>guest</strong>', '<li>Item</li>', '<td colspan="2">Value</td>', '<details>', '<summary>Expand</summary>', '<a>Link label</a>']) assert.ok(output.includes(expected), expected)
  assert.throws(() => staticHtml('<p>' + '&'.repeat(100) + '</p>', 200), /ceiling/)
  assert.doesNotThrow(() => staticHtml('<div>'.repeat(2000) + 'deep' + '</div>'.repeat(2000), 65536))
})
